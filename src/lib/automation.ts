import crypto from "node:crypto";
import { getDb } from "./db";

export interface WorkflowCondition {
  field: string;
  operator: "equals" | "contains" | "gt";
  value: string;
}

export interface WorkflowAction {
  type: "assign_owner" | "send_notification" | "create_task" | "create_project";
  value: string;
}

export function runWorkflowsForTrigger(
  orgId: string,
  triggerType: string,
  payload: Record<string, unknown>
) {
  const db = getDb();
  const workflows = db
    .prepare(
      `SELECT id, name, conditions_json, actions_json, run_count
       FROM workflows
       WHERE org_id = ? AND trigger_type = ? AND enabled = 1`
    )
    .all(orgId, triggerType) as Array<{
    id: string;
    name: string;
    conditions_json: string;
    actions_json: string;
    run_count: number;
  }>;

  const now = new Date().toISOString();

  for (const wf of workflows) {
    const conditions: WorkflowCondition[] = JSON.parse(wf.conditions_json || "[]");
    const matches = conditions.every((c) => {
      const actual = String(payload[c.field] ?? "");
      if (c.operator === "equals") return actual.toLowerCase() === c.value.toLowerCase();
      if (c.operator === "contains") return actual.toLowerCase().includes(c.value.toLowerCase());
      if (c.operator === "gt") return Number(actual) > Number(c.value);
      return true;
    });

    if (!matches) continue;

    const actions: WorkflowAction[] = JSON.parse(wf.actions_json || "[]");
    const logs: string[] = [];

    for (const action of actions) {
      if (action.type === "send_notification") {
        const users = db
          .prepare("SELECT id FROM users WHERE org_id = ? AND role != 'client' LIMIT 3")
          .all(orgId) as Array<{ id: string }>;
        for (const u of users) {
          db.prepare(
            `INSERT INTO notifications (id, org_id, user_id, title, body, link, read, created_at)
             VALUES (?, ?, ?, ?, ?, ?, 0, ?)`
          ).run(
            `notif_${crypto.randomUUID()}`,
            orgId,
            u.id,
            `Automation: ${wf.name}`,
            action.value,
            "/workflows",
            now
          );
        }
        logs.push(`Sent notification: "${action.value}"`);
      } else if (action.type === "create_task") {
        db.prepare(
          `INSERT INTO tasks (id, org_id, project_id, title, description, status, priority, due_date, created_at, updated_at)
           VALUES (?, ?, ?, ?, ?, 'Todo', 'High', ?, ?, ?)`
        ).run(
          `task_${crypto.randomUUID()}`,
          orgId,
          (payload.projectId as string) || null,
          `${action.value}${payload.name ? ` — ${payload.name}` : ""}`,
          `Auto-generated by workflow "${wf.name}"`,
          new Date(Date.now() + 86400000).toISOString().slice(0, 10),
          now,
          now
        );
        logs.push(`Created task: "${action.value}"`);
      } else if (action.type === "assign_owner" && payload.leadId) {
        db.prepare("UPDATE leads SET owner_id = ? WHERE id = ? AND org_id = ?").run(
          action.value,
          String(payload.leadId),
          orgId
        );
        logs.push(`Assigned lead owner: ${action.value}`);
      } else if (action.type === "create_project" && payload.quotationId) {
        const qt = db
          .prepare("SELECT * FROM quotations WHERE id = ? AND org_id = ?")
          .get(String(payload.quotationId), orgId) as
          | { id: string; title: string; client_name: string; client_email: string; total: number }
          | undefined;
        if (qt) {
          const projId = `proj_${crypto.randomUUID()}`;
          db.prepare(
            `INSERT INTO projects (id, org_id, quotation_id, name, description, client_name, client_email, status, progress, start_date, budget, created_at, updated_at)
             VALUES (?, ?, ?, ?, ?, ?, ?, 'Planning', 0, ?, ?, ?, ?)`
          ).run(
            projId,
            orgId,
            qt.id,
            qt.title,
            `Auto-created from approved quotation`,
            qt.client_name,
            qt.client_email,
            now.slice(0, 10),
            qt.total,
            now,
            now
          );
          payload.projectId = projId;
          logs.push(`Created project from quotation ${qt.id}`);
        }
      }
    }

    db.prepare(
      `UPDATE workflows SET run_count = run_count + 1, last_run_at = ? WHERE id = ?`
    ).run(now, wf.id);

    db.prepare(
      `INSERT INTO workflow_runs (id, org_id, workflow_id, trigger_payload_json, status, log_text, executed_at)
       VALUES (?, ?, ?, ?, 'Success', ?, ?)`
    ).run(
      `wfr_${crypto.randomUUID()}`,
      orgId,
      wf.id,
      JSON.stringify(payload),
      logs.join(" | "),
      now
    );
  }
}
